const originalText = new WeakMap();
const originalAttributes = new WeakMap();

const translatedValue = (source, language) => {
  if (language === 'fr') return source;
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const content = source.trim();
  const dynamicTranslation = content
    .replace(/^(\d+)\s+demandes?$/, (_, count) => `${count} ${count === '1' ? 'request' : 'requests'}`)
    .replace(/^Aucun camion disponible sur le trajet (.+) → (.+)\.$/, (_, origin, destination) => `No trucks are available on the route ${translations[origin] || origin} → ${translations[destination] || destination}.`)
    .replace(/^Aucune disponibilité compatible n’a été détectée pour le corridor (.+) → (.+) pendant la recherche de 1 minute\.$/, (_, origin, destination) => `No compatible truck availability was found on the ${translations[origin] || origin} → ${translations[destination] || destination} corridor after one minute of searching.`)
    .replace(/^(\d+)\s+en attente de camion$/, '$1 awaiting a truck')
    .replace(/^(\d+)\s+t de capacité totale$/, '$1 t total capacity')
    .replace(/^(\d+)\s+compte$/, (_, count) => `${count} ${count === '1' ? 'account' : 'accounts'}`)
    .replace(/^(\d+)\s+validé$/, '$1 approved')
    .replace(/^(\d+)\s+acteur avec documents$/, (_, count) => `${count} ${count === '1' ? 'user with documents' : 'users with documents'}`)
    .replace(/^(\d+)\s+opération\(s\)$/, (_, count) => `${count} ${count === '1' ? 'transaction' : 'transactions'}`)
    .replace(/^Page (\d+) sur (\d+)$/, 'Page $1 of $2')
    .replace(/^(\d+)-(\d+) sur (\d+)$/, '$1-$2 of $3')
    .replace(/^Avance(?=\s*[·:])/, 'Deposit')
    .replace(/^Solde(?=\s*[·:])/, 'Balance');
  const translated = translations[content]
    || dynamicTranslation;
  return translated !== content ? `${leading}${translated}${trailing}` : source;
};

const localizeNode = (node, language, refreshOriginal = false) => {
  if (node.nodeType === Node.TEXT_NODE) {
    if (refreshOriginal || !originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const translated = translatedValue(source, language);
    if (node.nodeValue !== translated) node.nodeValue = translated;
    return;
  }

  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (node.hasAttribute('data-language-switcher')) return;
  ATTRIBUTE_NAMES.forEach((name) => {
    if (!node.hasAttribute(name)) return;
    let attributes = originalAttributes.get(node);
    if (!attributes) {
      attributes = new Map();
      originalAttributes.set(node, attributes);
    }
    if (refreshOriginal || !attributes.has(name)) attributes.set(name, node.getAttribute(name));
    const source = attributes.get(name);
    const translated = translatedValue(source, language);
    if (node.getAttribute(name) !== translated) node.setAttribute(name, translated);
  });
  node.childNodes.forEach((child) => localizeNode(child, language, refreshOriginal));
};

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'fr';
    } catch {
      return 'fr';
    }
  });

  useEffect(() => {
    document.documentElement.lang = language;
    const root = document.getElementById('root');
    if (!root) return undefined;

    const observer = new MutationObserver((records) => {
      observer.disconnect();
      records.forEach((record) => {
        if (record.type === 'characterData') {
          localizeNode(record.target, language, true);
        } else if (record.type === 'attributes') {
          const element = record.target;
          const attributes = originalAttributes.get(element);
          if (attributes?.has(record.attributeName)) attributes.set(record.attributeName, element.getAttribute(record.attributeName));
          localizeNode(element, language);
        } else {
          record.addedNodes.forEach((node) => localizeNode(node, language, true));
        }
      });
      observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRIBUTE_NAMES });
    });

    localizeNode(root, language);
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRIBUTE_NAMES });
    return () => observer.disconnect();
  }, [language]);

  const setAndPersistLanguage = (nextLanguage) => {
    try {
      localStorage.setItem(STORAGE_KEY, nextLanguage);
    } catch {
      // The selected language still applies for this session when storage is unavailable.
    }
    setLanguage(nextLanguage);
  };
  const value = useMemo(() => ({
    language,
    setLanguage: setAndPersistLanguage,
    translate: (source) => translatedValue(String(source ?? ''), language),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
